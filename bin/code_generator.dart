class CodeGenerator {
  CodeGenerator(this.context, this.options);
  final GenerationContext context;
  final DepGenOptions options;

  Future<File> generateAndWrite() async {
    final current = Directory.current;
    final output = Directory.fromUri(Uri.parse(options.outputPath));
    final outputFile = File(path.join(output.path, options.outputFile));

    // Prepare output file
    if (!outputFile.existsSync()) {
      outputFile.createSync(recursive: true);
    } else {
      outputFile
        ..deleteSync()
        ..createSync(recursive: true);
    }
    print('ℹ️  Generated file = $outputFile');

    final StringBuffer outBuffer = StringBuffer();
    _writeHeaderContent(outBuffer);

    // Generate methods for all constructors
    for (final maker in context.constructorsToGenerate) {
      _writeConstructorsMethod(maker.declaration, maker.constructor, outBuffer);
    }

    _writeFooterContent(outBuffer);

    // Open sink to write file
    final IOSink outputSink = outputFile.openWrite()

      // Write common file header (imports block start)
      ..write(_getCommonFileHeader(options.commandLine));

    // Write external packages list (from --imported-packages)
    for (final package in context.importedPackages) {
      outputSink.write('$package\n');
    }

    // Remove nullable signs and unused imports
    context.usedClasses
        .map((e) => e.replaceAll('?', ''))
        .forEach(context.usedClasses.add);
    context.allClassesPath
        .removeWhere((key, value) => !context.usedClasses.contains(key));

    // Write used external packages (from @DepArg(package: '...'))
    context.usedExternalPaths
        .forEach((key, value) => outputSink.write('$value\n'));

    // Convert local imports to package dependencies
    late final String pathSeparator;
    try {
      pathSeparator = Platform.pathSeparator;
    } on Object {
      pathSeparator = '/';
    }
    final int currentPathLength = current.path.length;

    final Set<String> usedPaths = context.allClassesPath.entries
        .map((e) => e.value.substring(currentPathLength))
        .map((e) =>
            '${e.replaceFirst('${pathSeparator}lib$pathSeparator', 'import \'package:${context.packageName}/')}\';')
        .map((e) => e.replaceAll(Platform.pathSeparator, '/'))
        .toSet();

    // Write internal dependencies to file
    for (final value in usedPaths) {
      outputSink.write('$value\n');
    }

    // Write all generated build methods
    outputSink
      ..write('\n')
      ..write(outBuffer.toString())
      ..write('''
  
// coverage:ignore-end
  ''');
    await outputSink.close();

    return outputFile;
  }

  String _getCommonFileHeader(String commandLine) {
    return """
// GENERATED CODE - DO NOT MODIFY BY HAND

// ignore_for_file: type=lint
// coverage:ignore-start

import 'dart:collection';

import 'package:flutter/widgets.dart';
import 'package:meta/meta.dart';

// **************************************************************************
// DepGen code generator
// This file was generated by running the command: 
// flutter pub run dep_gen:generate $commandLine
// **************************************************************************

""";
  }

  void _writeHeaderContent(StringBuffer outputSink) {
    outputSink.write("""

/// The environment in which all used dependency instances are configured
@immutable
class DepGenEnvironment {
  DepGenEnvironment({Map<Type, Object>? initialServices})
      : _environment = initialServices ?? {};

  late final Map<Type, Object> _environment;

  // ---------------------------------------------------------------------------
  /// An unsafe method for getting an instance by its type. You need to be sure
  /// that an instance of the requested type has been registered
  T g<T>() => _environment[T] as T;

  // ---------------------------------------------------------------------------
  /// A safe method for trying to get an instance by its type.
  T? mayBeGet<T>() => _environment.containsKey(T) ? _environment[T] as T : null;

  // ---------------------------------------------------------------------------
  /// Registration of an instance with an indication of its type. You cannot
  /// register multiple instances of the same type
  void registry<T>(Object instance) => _environment[T] = instance;

  // ---------------------------------------------------------------------------
  /// Is the collection of instances blocked
  bool get isLocked => _environment is UnmodifiableMapView;

  // ---------------------------------------------------------------------------
  /// Returns an instance of the environment settings with the collection
  /// blocked from changes
  DepGenEnvironment lock() {
    return DepGenEnvironment(initialServices: Map.unmodifiable(_environment));
  }
}

